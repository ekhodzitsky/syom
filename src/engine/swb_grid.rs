pub(super) fn long_960(fs_index: u8) -> Result<&'static [u16]> {
    let table = match fs_index {
        0..=1 => L960_96,
        2 => L960_64,
        3..=5 => L960_48,
        6..=7 => L960_24,
        8..=10 => L960_16,
        11 => L960_8,
        _ => return Err(Error::UnsupportedSampleRateIndex(fs_index)),
    };
    Ok(table)
}

pub(super) fn short_120(fs_index: u8) -> Result<&'static [u16]> {
    let table = match fs_index {
        0..=2 => S120_96,
        3..=5 => S120_48,
        6..=7 => S120_24,
        8..=10 => S120_16,
        11 => S120_8,
        _ => return Err(Error::UnsupportedSampleRateIndex(fs_index)),
    };
    Ok(table)
}

pub(super) fn long_480(fs_index: u8) -> Result<&'static [u16]> {
    let table = match fs_index {
        3..=4 => LD480_48,
        5 => LD480_32,
        6..=7 => LD480_24,
        _ => return Err(Error::UnsupportedSampleRateIndex(fs_index)),
    };
    Ok(table)
}
